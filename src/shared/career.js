/* answers: массив из 24 чисел 0|1|2 (а|б|в). Возвращает баллы по шести шкалам (0–12). */
export function scoreCareer(answers) {
  const scores = [0, 0, 0, 0, 0, 0];
  answers.forEach((answer, index) => {
    const scale = CAREER_KEY[index]?.[answer];
    if (scale) scores[scale - 1] += 1;
  });
  return scores;
}

export function careerLevel(score) {
  if (score >= 10) return { key: 'high', label: 'ярко выражена' };
  if (score >= 7) return { key: 'mid', label: 'склонность' };
  if (score >= 4) return { key: 'low', label: 'слабо выражена' };
  return { key: 'none', label: 'не выражена' };
}

export function validCareerAnswers(answers) {
  return Array.isArray(answers) && answers.length === CAREER_QUESTIONS.length && answers.every((a) => Number.isInteger(a) && a >= 0 && a <= 2);
}
