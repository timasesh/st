export const DIFFICULTY = (index: number, total = 10) => {
  const share = (index + 1) / total;
  if (share <= 0.3) return { label: 'Лёгкий', tone: 'emerald' as const };
  if (share <= 0.6) return { label: 'Средний', tone: 'amber' as const };
  if (share <= 0.8) return { label: 'Повышенный', tone: 'orange' as const };
  return { label: 'Сложный', tone: 'rose' as const };
};

