export function resultLevel(score: number, total: number) {
  const share = score / total;
  if (share >= 0.9) return { title: 'Отличный уровень', text: 'Вы уверенно владеете программой. Можно браться за олимпиадные и нестандартные задачи.', emoji: '🏆' };
  if (share >= 0.7) return { title: 'Хороший уровень', text: 'База крепкая, есть несколько тем, которые стоит подтянуть, чтобы выйти на отлично.', emoji: '🚀' };
  if (share >= 0.4) return { title: 'Средний уровень', text: 'Есть пробелы в базе. С ними лучше разобраться сейчас, пока они не накопились.', emoji: '📈' };
  return { title: 'Нужна поддержка', text: 'Ничего страшного: пробелы закрываются. С регулярной практикой и наставником результат вырастет быстро.', emoji: '🌱' };
}
